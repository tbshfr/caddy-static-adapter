// checkInterval is the fallback polling interval used when filesystem
// notifications are unavailable.
const checkInterval = 2 * time.Second

// debounceDelay is the time to wait after the last fsnotify event before
// reloading. This avoids reacting to intermediate file states during saves
// (e.g., editors that truncate then write, producing a brief empty file).
const debounceDelay = 100 * time.Millisecond

// maxCachedFiles bounds how many distinct file paths one handler caches.
// The path follows the root directive, which may depend on the request
// (e.g. root * /srv/{host}), so the cache must not grow without limit.
const maxCachedFiles = 64

// clockStart anchors monotonicNow.
var clockStart = time.Now()

// monotonicNow returns the nanoseconds since clockStart, read from the
// monotonic clock. With Unix time, a wall-clock step back (NTP, VM resume)
// would suspend checks until the clock caught up again.
func monotonicNow() int64 {
	return int64(time.Since(clockStart))
}

// cachedFile holds the compiled data and reload state for one file path.
// data and lastCheck are read without locking on every request; the other
// fields are guarded by fileHandler.mu.
type cachedFile struct {
	data      atomic.Pointer[any] // handler-specific compiled data (e.g. *Compiled or *CompiledRedirects)
	lastCheck atomic.Int64        // monotonicNow() at the last check

	loaded  os.FileInfo // file version data was loaded from; nil before the first successful load
	watched bool        // whether the file's directory is subscribed in sharedWatcher
	lastErr string      // last load error, so a persisting error is logged only once
}

func (f *cachedFile) get() any {
	if p := f.data.Load(); p != nil {
		return *p
	}
	return nil
}

func (f *cachedFile) set(data any) {
	if data == nil {
		f.data.Store(nil)
		return
	}
	f.data.Store(&data)
}

// fileHandler provides shared file-watching, caching, and reload
// infrastructure for handlers that monitor a configuration file on disk.
// Both the headers and redirects handlers embed this type to avoid
// duplicating the polling / fsnotify / caching logic.
type fileHandler struct {
	// Strict controls whether parse errors reject the whole file. A
	// rejected file keeps the previously loaded rules active until a
	// valid version is loaded. When false (default), parse warnings are
	// logged but valid rules still apply.
	Strict bool `json:"strict,omitempty"`

	// MaxRules is the maximum number of rules allowed.
	MaxRules int `json:"max_rules,omitempty"`

	// MaxFileSize is the maximum file size in bytes (default: 1 MB).
	MaxFileSize int `json:"max_file_size,omitempty"`

	// MaxLineLength is the maximum number of characters allowed per line.
	MaxLineLength int `json:"max_line_length,omitempty"`

	// Dedup controls whether duplicate header names across matching
	// rules use "most specific wins" semantics instead of comma-joining.
	// When enabled, matching rules are sorted by pattern specificity
	// (more literal characters beat fewer, exact matches beat wildcards)
	// so that the most specific rule's value takes precedence.
	// This is useful when consuming _headers files generated by
	// frameworks where overlapping wildcard rules set
	// the same header at different specificity levels.
	// Fix for https://github.com/nitrojs/nitro/pull/3938 until its merged
	Dedup bool `json:"dedup,omitempty"`

	// mu serializes checks and reloads. Requests never wait for it unless
	// they are the first for a file path.
	mu sync.Mutex
	// files maps file paths to cache entries. The map is never modified;
	// adding or evicting an entry stores a new map, under mu.
	files atomic.Pointer[map[string]*cachedFile]

	logger    *zap.Logger
	logPrefix string // e.g. "static_headers" or "static_redirects"
	fileName  string // basename to watch, e.g. "_headers" or "_redirects"

	debounceMu sync.Mutex
	debounce   map[string]*time.Timer // pending watcher reloads by file path
	closed     atomic.Bool            // set by Cleanup

	// loadFn is called under mu to load and compile the file.
	// It returns the handler-specific compiled data, or an error when the
	// file could not be read or was rejected in strict mode.
	loadFn func(filePath string) (any, error)
}

// getCached returns the cached compiled data for the given file path,
// reloading from disk when the file has changed. The filesystem watcher
// proactively reloads in the background; time-based polling acts as a
// fallback when the watcher is unavailable.
//
// A cache hit takes no lock. When an entry is due for a check, the request
// that wins the compare-and-swap on lastCheck performs it, while concurrent
// requests keep serving the current rules instead of queueing behind it.
func (fh *fileHandler) getCached(filePath string) any {
	now := monotonicNow()

	if f := fh.lookup(filePath); f != nil {
		last := f.lastCheck.Load()
		if now-last >= int64(checkInterval) && f.lastCheck.CompareAndSwap(last, now) {
			fh.mu.Lock()
			// The entry may have been evicted while this request waited.
			// Subscribing it again would leave a watch that Cleanup can't
			// find, keeping this handler alive in sharedWatcher.
			if fh.lookup(filePath) == f {
				fh.ensureWatchingLocked(filePath, f)
				fh.refreshLocked(filePath, f, false)
			}
			fh.mu.Unlock()
		}
		return f.get()
	}

	fh.mu.Lock()
	defer fh.mu.Unlock()

	// Another request may have added the entry while this one waited.
	if f := fh.lookup(filePath); f != nil {
		return f.get()
	}

	// Publish the entry only after its first load, so concurrent requests
	// never see it without rules.
	f := &cachedFile{}
	f.lastCheck.Store(now)
	fh.ensureWatchingLocked(filePath, f)
	fh.refreshLocked(filePath, f, false)
	fh.addFileLocked(filePath, f)
	return f.get()
}

// lookup returns the cache entry for filePath, or nil.
func (fh *fileHandler) lookup(filePath string) *cachedFile {
	if files := fh.files.Load(); files != nil {
		return (*files)[filePath]
	}
	return nil
}

// addFileLocked publishes a cache entry for filePath, evicting the least
// recently checked entry when the cache is full. Entries without rules (a
// missing or rejected file) are evicted first, so requests for many
// nonexistent roots, e.g. random Host headers with root /srv/{host}, can't
// push out loaded rules and force them to be parsed again. Must be called
// with fh.mu held.
func (fh *fileHandler) addFileLocked(filePath string, f *cachedFile) {
	var current map[string]*cachedFile
	if files := fh.files.Load(); files != nil {
		current = *files
	}

	next := make(map[string]*cachedFile, len(current)+1)
	for p, e := range current {
		next[p] = e
	}
	if len(next) >= maxCachedFiles {
		var oldestPath string
		var oldest *cachedFile
		for p, e := range next {
			if oldest == nil || evictBefore(e, oldest) {
				oldestPath, oldest = p, e
			}
		}
		if oldest.watched {
			sharedWatcher.unsubscribe(filepath.Dir(oldestPath), fh)
			oldest.watched = false
		}
		delete(next, oldestPath)
	}

	next[filePath] = f
	fh.files.Store(&next)
}

// evictBefore reports whether a should be evicted before b.
func evictBefore(a, b *cachedFile) bool {
	if aEmpty, bEmpty := a.get() == nil, b.get() == nil; aEmpty != bEmpty {
		return aEmpty
	}
	return a.lastCheck.Load() < b.lastCheck.Load()
}

// refreshLocked stats filePath and reloads it when it changed since the
// last successful load, or unconditionally when force is set. Must be
// called with fh.mu held.
//
// A failed load, or one the file changed during, keeps the previously
// loaded rules, so a broken deploy does not silently strip headers such as
// a CSP. Failures are retried on every check (fixing permissions doesn't
// change the mtime), but each distinct error is logged only once.
func (fh *fileHandler) refreshLocked(filePath string, f *cachedFile, force bool) {
	info, err := statIdentity(filePath)
	if os.IsNotExist(err) {
		f.set(nil)
		f.lastErr = ""
		return
	}
	if err != nil {
		fh.logLoadErrorLocked(filePath, f, fmt.Errorf("failed to stat file: %w", err))
		return
	}

	if !force && f.get() != nil && f.lastErr == "" && !fileChanged(f.loaded, info) {
		return
	}

	data, err := fh.loadFn(filePath)
	if err != nil {
		fh.logLoadErrorLocked(filePath, f, err)
		return
	}
	// A file rewritten in place (cp over it, an editor saving) is empty or
	// partly written for a moment. If it changed while being read, the
	// rules may be from such a state, so the previous ones stay active and
	// the change's watcher event, or the next check, loads it again. With
	// no previous rules, the rules read are still better than none.
	if after, err := statIdentity(filePath); err != nil || fileChanged(info, after) {
		fh.logger.Info(fh.logPrefix+": file changed while loading, loading it again on the next check",
			zap.String("file", filePath),
			zap.Bool("keeping_previous_rules", f.get() != nil))
		if f.get() == nil {
			f.set(data)
			f.lastErr = ""
		}
		return
	}
	f.set(data)
	f.loaded = info
	f.lastErr = ""
}

// fileChanged reports whether info describes a different version of the
// file than loaded. Comparing size and identity (inode) besides the mtime
// catches deploys that preserve mtimes (rsync -t, cp -p, Nix) as long as
// they replace the file or change its size; atomic renames, symlink swaps
// and directory swaps always produce a new identity.
func fileChanged(loaded, info os.FileInfo) bool {
	return loaded == nil ||
		!os.SameFile(loaded, info) ||
		loaded.Size() != info.Size() ||
		!loaded.ModTime().Equal(info.ModTime())
}

// statIdentity is os.Stat that also reads the file's identity right away.
// On Windows, os.Stat only records the path and os.SameFile reads the file
// ID on first use, which after a deploy replaced the file would already be
// the new file's.
func statIdentity(name string) (os.FileInfo, error) {
	info, err := os.Stat(name)
	if err == nil {
		os.SameFile(info, info)
	}
	return info, err
}

// logLoadErrorLocked logs err unless it is the same error that was last
// logged for this file. Must be called with fh.mu held.
func (fh *fileHandler) logLoadErrorLocked(filePath string, f *cachedFile, err error) {
	if err.Error() == f.lastErr {
		return
	}
	f.lastErr = err.Error()
	fh.logger.Error(fh.logPrefix+": failed to load file",
		zap.String("file", filePath),
		zap.Bool("keeping_previous_rules", f.get() != nil),
		zap.Error(err))
}

// ensureWatchingLocked subscribes the directory of filePath in the shared
// filesystem watcher so that changes are detected instantly. Falls back to
// polling if the directory cannot be watched. Called on every check, so a
// replaced directory is re-watched. Must be called with fh.mu held.
func (fh *fileHandler) ensureWatchingLocked(filePath string, f *cachedFile) {
	if fh.closed.Load() {
		return
	}

	dir := filepath.Dir(filePath)
	if err := sharedWatcher.subscribe(dir, fh); err != nil {
		f.watched = false
		// A missing directory is picked up by polling once it appears.
		if !os.IsNotExist(err) {
			fh.logger.Warn(fh.logPrefix+": failed to watch directory, falling back to polling",
				zap.String("dir", dir),
				zap.Error(err))
		}
		return
	}
	f.watched = true
}

// scheduleReload reloads filePath after debounceDelay, restarting the delay
// when called again before it expires, so that rapid event sequences
// (e.g., truncate + write) coalesce into a single reload.
func (fh *fileHandler) scheduleReload(filePath string) {
	fh.debounceMu.Lock()
	defer fh.debounceMu.Unlock()

	if fh.closed.Load() {
		return
	}
	if t := fh.debounce[filePath]; t != nil {
		t.Stop()
	}
	if fh.debounce == nil {
		fh.debounce = make(map[string]*time.Timer)
	}

	var t *time.Timer
	t = time.AfterFunc(debounceDelay, func() {
		fh.debounceMu.Lock()
		if fh.debounce[filePath] == t {
			delete(fh.debounce, filePath)
		}
		fh.debounceMu.Unlock()
		fh.reloadInBackground(filePath)
	})
	fh.debounce[filePath] = t
}

// reloadInBackground proactively reloads a watched file when a
// filesystem event is detected, so compiled rules are up-to-date
// before the next request arrives.
func (fh *fileHandler) reloadInBackground(filePath string) {
	f := fh.lookup(filePath)
	if f == nil {
		return // evicted since the event was queued
	}

	fh.mu.Lock()
	defer fh.mu.Unlock()
	f.lastCheck.Store(monotonicNow())
	fh.refreshLocked(filePath, f, true)
}

// Cleanup releases resources held by the file handler.
func (fh *fileHandler) Cleanup() error {
	fh.closed.Store(true)

	fh.debounceMu.Lock()
	for _, t := range fh.debounce {
		t.Stop()
	}
	fh.debounce = nil
	fh.debounceMu.Unlock()

	fh.mu.Lock()
	defer fh.mu.Unlock()
	if files := fh.files.Load(); files != nil {
		for p, f := range *files {
			if f.watched {
				sharedWatcher.unsubscribe(filepath.Dir(p), fh)
				f.watched = false
			}
		}
	}
	return nil
}

// unmarshalCaddyfile parses the shared Caddyfile options (strict,
// max_rules, max_file_size, max_line_length) that are common to
// both the headers and redirects handlers.
func (fh *fileHandler) unmarshalCaddyfile(d *caddyfile.Dispenser) error {
	d.Next() // consume directive name

	for d.NextBlock(0) {
		switch d.Val() {
		case "strict":
			fh.Strict = true
		case "dedup":
			fh.Dedup = true
		case "max_rules":
			if !d.NextArg() {
				return d.ArgErr()
			}
			val, err := strconv.Atoi(d.Val())
			if err != nil {
				return d.Errf("invalid max_rules value: %v", err)
			}
			fh.MaxRules = val
		case "max_file_size":
			if !d.NextArg() {
				return d.ArgErr()
			}
			val, err := strconv.Atoi(d.Val())
			if err != nil {
				return d.Errf("invalid max_file_size value: %v", err)
			}
			fh.MaxFileSize = val
		case "max_line_length":
			if !d.NextArg() {
				return d.ArgErr()
			}
			val, err := strconv.Atoi(d.Val())
			if err != nil {
				return d.Errf("invalid max_line_length value: %v", err)
			}
			fh.MaxLineLength = val
		default:
			return d.Errf("unrecognized option: %s", d.Val())
		}
	}

	return nil
}

// Interface guard: fileHandler satisfies caddy.CleanerUpper.
var _ caddy.CleanerUpper = (*fileHandler)(nil)
